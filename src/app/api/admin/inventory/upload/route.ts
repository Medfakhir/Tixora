import { z } from 'zod'
import { withApi, ok, readFormData, ApiError } from '@/lib/api/http'
import { adminRequest } from '@/lib/api/admin'
import { prisma } from '@/lib/db/prisma'
import { getStorage } from '@/lib/storage'
import { assertBatchLimits, validatePdf, sanitiseFileName, MAX_BATCH_FILES } from '@/lib/storage/pdf'
import { recordAudit } from '@/lib/auth/guards'

const querySchema = z.object({
  productId: z.string().min(1),
  eventSessionId: z.string().min(1).optional().or(z.literal('')),
  /** Model B only: how many tickets one uploaded file represents. */
  groupTicketCount: z.coerce.number().int().min(1).max(1000).default(1),
})

/**
 * Uploads are the only place raw bytes from a browser reach storage. Nothing here trusts a
 * filename, a content type or a file count: names are sanitised for display, bytes are
 * signature-checked, and keys are generated by the storage adapter.
 */
export const POST = withApi(async (request: Request) => {
  const { admin, ip } = await adminRequest(request, 'sensitive')
  const form = await readFormData(request)

  const payload = querySchema.parse({
    productId: form.get('productId'),
    eventSessionId: form.get('eventSessionId') ?? '',
    groupTicketCount: form.get('groupTicketCount') ?? 1,
  })

  const files = form.getAll('files').filter((entry): entry is File => entry instanceof File && entry.size > 0)
  if (files.length === 0) throw new ApiError('No files were received.', 422, 'NO_FILES')
  if (files.length > MAX_BATCH_FILES) throw new ApiError(`A batch is limited to ${MAX_BATCH_FILES} files.`, 413, 'TOO_MANY_FILES')

  const batchError = assertBatchLimits(files.map((file) => ({ size: file.size })))
  if (batchError) throw new ApiError(batchError, 413, 'BATCH_TOO_LARGE')

  const product = await prisma.product.findUnique({ where: { id: payload.productId } })
  if (!product) throw new ApiError('Product not found.', 404, 'NOT_FOUND')

  const eventSessionId = payload.eventSessionId || null
  if (product.requiresSession && !eventSessionId) {
    throw new ApiError('This product sells per event session; choose one before uploading.', 422, 'SESSION_REQUIRED', {
      eventSessionId: 'Required',
    })
  }
  if (eventSessionId) {
    const session = await prisma.eventSession.findFirst({ where: { id: eventSessionId, productId: product.id }, select: { id: true } })
    if (!session) throw new ApiError('That session does not belong to this product.', 422, 'SESSION_MISMATCH')
  }

  // Model B is opt-in per product; a Model A product always counts one ticket per file.
  const ticketCount = product.inventoryModel === 'ONE_PDF_PER_GROUP' ? payload.groupTicketCount : 1
  const storage = getStorage()
  const accepted: { id: string; fileName: string; storageKey: string; ticketCount: number }[] = []
  const rejected: { fileName: string; reason: string }[] = []

  for (const file of files) {
    const buffer = Buffer.from(await file.arrayBuffer())
    const validated = validatePdf(buffer, file.name, file.type)
    if (!validated.ok) {
      rejected.push({ fileName: sanitiseFileName(file.name), reason: validated.reason })
      continue
    }
    const display = validated.sanitisedFileName

    // The same PDF twice would put two identical tickets into one paid order.
    const duplicate = await prisma.ticketInventory.findFirst({
      where: { productId: product.id, checksum: validated.checksum, status: { not: 'RETIRED' } },
      select: { id: true },
    })
    if (duplicate) {
      rejected.push({ fileName: display, reason: 'An identical file is already in inventory for this product.' })
      continue
    }

    const stored = await storage.put({ body: buffer, contentType: 'application/pdf', suggestedExtension: 'pdf', namespace: 'tickets' })
    const row = await prisma.ticketInventory.create({
      data: {
        productId: product.id,
        eventSessionId,
        storageKey: stored.key,
        originalFileName: display,
        fileSize: buffer.byteLength,
        mimeType: 'application/pdf',
        checksum: validated.checksum,
        ticketCount,
        status: 'AVAILABLE',
      },
    })
    accepted.push({ id: row.id, fileName: display, storageKey: stored.key, ticketCount })
  }

  await recordAudit({
    actorType: 'ADMIN',
    actorId: admin.id,
    actorLabel: admin.email,
    action: 'INVENTORY_UPLOAD',
    entityType: 'Product',
    entityId: product.id,
    summary: `Uploaded ${accepted.length} PDF(s) for ${product.name}${rejected.length ? `, rejected ${rejected.length}` : ''}`,
    metadata: {
      eventSessionId,
      ticketCount,
      accepted: accepted.map((entry) => entry.fileName),
      rejected,
    },
    ip,
  })

  return ok({ accepted, rejected }, accepted.length > 0 ? 201 : 422)
})
